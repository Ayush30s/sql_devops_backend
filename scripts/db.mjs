// Local PostgreSQL for development, without Docker: two project-local clusters built
// from the PostgreSQL binaries already installed on this machine.
//   app      application data (Prisma)                 localhost:54320
//   sandbox  SQL practice sandbox (restricted roles)    localhost:54321
//
//   node scripts/db.mjs init                 create clusters, roles, databases and .env
//   node scripts/db.mjs start [--if-local]   start clusters (no-op without local clusters)
//   node scripts/db.mjs stop | status
//   node scripts/db.mjs sandbox-setup        (re)apply sandbox roles/privileges; works against
//                                            any server via SANDBOX_ADMIN_URL
import { spawnSync } from "node:child_process";
import { appendFileSync, existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { join, resolve } from "node:path";
import pg from "pg";

// The backend is its own repository: its .env and its .data live next to its package.json.
const root = resolve(import.meta.dirname, "..");
const envFile = join(root, ".env");
const dataRoot = join(root, ".data", "postgres");
const credsFile = join(dataRoot, "credentials.json");
const CLUSTERS = { app: 54320, sandbox: 54321 };
const isWin = process.platform === "win32";

const fail = (msg) => {
  console.error(`✗ ${msg}`);
  process.exit(1);
};
const secret = () => randomBytes(18).toString("base64url");

function pgBin() {
  if (process.env.PG_BIN) return process.env.PG_BIN;
  const exe = isWin ? "pg_ctl.exe" : "pg_ctl";
  const versioned = (base) =>
    existsSync(base)
      ? readdirSync(base)
          .filter((v) => /^\d+/.test(v))
          .sort((a, b) => parseFloat(b) - parseFloat(a))
          .map((v) => join(base, v, "bin"))
      : [];
  const dirs = (process.env.PATH ?? "").split(isWin ? ";" : ":");
  dirs.push(...versioned(isWin ? "C:\\Program Files\\PostgreSQL" : "/usr/lib/postgresql"));
  const dir = dirs.find((d) => d && existsSync(join(d, exe)));
  if (!dir) fail("PostgreSQL binaries not found. Install PostgreSQL 14+ or set PG_BIN to its bin directory.");
  return dir;
}

// windowsHide: on Windows each tool, and so the server pg_ctl starts, gets its own hidden console.
// Sharing ours instead, the server outlives the terminal that ran `npm run dev` but can no longer
// start the process every new connection needs (0xC0000142), so all connections hang.
function pgTool(name, args, stdio = "pipe") {
  return spawnSync(join(pgBin(), isWin ? `${name}.exe` : name), args, { encoding: "utf8", stdio, windowsHide: true });
}

const clusterDir = (name) => join(dataRoot, name);
const hasLocalClusters = () => Object.keys(CLUSTERS).every((n) => existsSync(join(clusterDir(n), "PG_VERSION")));
const running = (name) => pgTool("pg_ctl", ["status", "-D", clusterDir(name)]).status === 0;

function start(name) {
  if (running(name)) return console.log(`✓ ${name} database running on port ${CLUSTERS[name]}`);
  const dir = clusterDir(name);
  // stdio "ignore": the detached server must not inherit our pipes.
  const r = pgTool("pg_ctl", ["start", "-w", "-t", "60", "-D", dir, "-l", join(dir, "server.log")], "ignore");
  if (r.status !== 0) fail(`Could not start the ${name} database. See ${join(dir, "server.log")}`);
  console.log(`✓ ${name} database started on port ${CLUSTERS[name]}`);
}

function stop(name) {
  if (!running(name)) return console.log(`• ${name} database not running`);
  const r = pgTool("pg_ctl", ["stop", "-w", "-m", "fast", "-D", clusterDir(name)], "ignore");
  if (r.status !== 0) fail(`Could not stop the ${name} database. See ${join(clusterDir(name), "server.log")}`);
  console.log(`✓ ${name} database stopped`);
}

function readEnv() {
  if (!existsSync(envFile)) return {};
  const env = {};
  for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*"?(.*?)"?\s*$/);
    if (m) env[m[1]] = m[2];
  }
  return env;
}

function addMissingEnv(values) {
  const env = readEnv();
  const missing = Object.entries(values).filter(([k]) => !(k in env));
  if (missing.length) {
    const header = existsSync(envFile) ? "\n" : "# Generated by `npm run setup` for local development.\n";
    appendFileSync(envFile, header + missing.map(([k, v]) => `${k}="${v}"`).join("\n") + "\n");
  }
  return { ...Object.fromEntries(missing), ...env };
}

async function withClient(url, fn) {
  const client = new pg.Client({ connectionString: url });
  await client.connect();
  try {
    return await fn(client);
  } finally {
    await client.end();
  }
}

async function ensureRole(c, name, password, options = "") {
  const exists = (await c.query("SELECT 1 FROM pg_roles WHERE rolname = $1", [name])).rowCount;
  const verb = exists ? "ALTER" : "CREATE";
  await c.query(`${verb} ROLE ${c.escapeIdentifier(name)} WITH LOGIN PASSWORD ${c.escapeLiteral(password)} ${options}`);
}

async function ensureDatabase(c, name, owner) {
  if (!(await c.query("SELECT 1 FROM pg_database WHERE datname = $1", [name])).rowCount)
    await c.query(`CREATE DATABASE ${c.escapeIdentifier(name)} OWNER ${c.escapeIdentifier(owner)}`);
}

// Best effort: some settings/functions differ between PostgreSQL versions and managed services.
let skipped = 0;

async function tryQuery(c, sql) {
  try {
    await c.query(sql);
  } catch (e) {
    skipped++;
    console.warn(`  ! skipped: ${sql.slice(0, 70)}… (${e.message})`);
  }
}

async function sandboxSetup(adminUrl, env) {
  const learner = new URL(env.SANDBOX_DATABASE_URL);
  const supervisor = new URL(env.SANDBOX_SUPERVISOR_URL);
  const db = learner.pathname.slice(1);
  const L = learner.username;
  const S = supervisor.username;

  await withClient(adminUrl, async (c) => {
    await ensureRole(c, L, decodeURIComponent(learner.password), "NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION CONNECTION LIMIT 30");
    await ensureRole(c, S, decodeURIComponent(supervisor.password), "NOSUPERUSER NOCREATEDB NOCREATEROLE CONNECTION LIMIT 5");
    await tryQuery(c, `GRANT pg_signal_backend TO ${c.escapeIdentifier(S)}`);
    await ensureDatabase(c, db, new URL(adminUrl).username);
    // Defaults the learner role cannot exceed without plpgsql tricks (which the app watchdog covers).
    for (const setting of [
      "statement_timeout = '3s'",
      "lock_timeout = '1s'",
      "idle_in_transaction_session_timeout = '10s'",
      "transaction_timeout = '10s'",
      "temp_file_limit = '64MB'",
      "work_mem = '4MB'",
    ])
      await tryQuery(c, `ALTER ROLE ${c.escapeIdentifier(L)} SET ${setting}`);
  });

  const dbUrl = new URL(adminUrl);
  dbUrl.pathname = `/${db}`;
  await withClient(dbUrl.toString(), async (c) => {
    const d = c.escapeIdentifier(db);
    const l = c.escapeIdentifier(L);
    const s = c.escapeIdentifier(S);
    for (const sql of [
      `REVOKE ALL ON DATABASE ${d} FROM PUBLIC`,
      `GRANT CONNECT, CREATE, TEMPORARY ON DATABASE ${d} TO ${l}`,
      `GRANT CONNECT ON DATABASE ${d} TO ${s}`,
      `REVOKE ALL ON SCHEMA public FROM PUBLIC`,
      // Learners must not change their own limits, see other sessions, or signal other backends.
      `REVOKE EXECUTE ON FUNCTION pg_catalog.set_config(text, text, boolean) FROM PUBLIC`,
      `REVOKE EXECUTE ON FUNCTION pg_catalog.pg_cancel_backend(integer) FROM PUBLIC`,
      `REVOKE EXECUTE ON FUNCTION pg_catalog.pg_terminate_backend(integer, bigint) FROM PUBLIC`,
      `REVOKE EXECUTE ON FUNCTION pg_catalog.pg_stat_get_activity(integer) FROM PUBLIC`,
      `REVOKE SELECT ON pg_catalog.pg_stat_activity FROM PUBLIC`,
      `GRANT EXECUTE ON FUNCTION pg_catalog.pg_terminate_backend(integer, bigint) TO ${s}`,
      `GRANT EXECUTE ON FUNCTION pg_catalog.pg_stat_get_activity(integer) TO ${s}`,
      `GRANT SELECT ON pg_catalog.pg_stat_activity TO ${s}`,
    ])
      await tryQuery(c, sql);
  });
  console.log(`✓ sandbox roles ready (${L}, ${S}) in database "${db}"`);
  if (skipped)
    console.warn(
      `\n! ${skipped} hardening statement(s) could not be applied.\n` +
        `  Revoking the pg_catalog functions needs superuser, which managed PostgreSQL does not give you.\n` +
        `  The sandbox still runs in its own database, in a transaction that is never committed, behind the\n` +
        `  statement allow-list and the app's watchdog — but learners share one role, so on a managed server\n` +
        `  they could read pg_stat_activity or cancel each other's queries.\n` +
        `  For a public deployment, run the sandbox on a PostgreSQL where you are superuser.`,
    );
}

async function init() {
  mkdirSync(dataRoot, { recursive: true });
  const creds = existsSync(credsFile) ? JSON.parse(readFileSync(credsFile, "utf8")) : {};
  for (const [name, port] of Object.entries(CLUSTERS)) {
    const dir = clusterDir(name);
    if (existsSync(join(dir, "PG_VERSION"))) {
      console.log(`• ${name} cluster already exists`);
      continue;
    }
    creds[name] ??= secret();
    const pwfile = join(dataRoot, `.pw-${name}`);
    writeFileSync(pwfile, creds[name]);
    try {
      const r = pgTool("initdb", ["-D", dir, "-U", "postgres", `--pwfile=${pwfile}`, "-A", "scram-sha-256", "-E", "UTF8", "--locale=C"]);
      if (r.status !== 0) fail(`initdb failed for ${name}:\n${r.stderr || r.stdout}`);
    } finally {
      unlinkSync(pwfile);
    }
    const tuning =
      name === "sandbox"
        ? ["max_connections = 40", "shared_buffers = 64MB", "work_mem = 4MB", "temp_file_limit = 128MB", "log_min_messages = warning"]
        : ["max_connections = 50"];
    appendFileSync(join(dir, "postgresql.conf"), ["", `port = ${port}`, "listen_addresses = 'localhost'", ...tuning, ""].join("\n"));
    console.log(`✓ created ${name} cluster`);
  }
  writeFileSync(credsFile, JSON.stringify(creds, null, 2));
  for (const name of Object.keys(CLUSTERS)) start(name);

  const env = addMissingEnv({
    DATABASE_URL: `postgresql://dsa:${secret()}@localhost:${CLUSTERS.app}/dsa`,
    SANDBOX_DATABASE_URL: `postgresql://learner:${secret()}@localhost:${CLUSTERS.sandbox}/sandbox`,
    SANDBOX_SUPERVISOR_URL: `postgresql://supervisor:${secret()}@localhost:${CLUSTERS.sandbox}/sandbox`,
    PORT: "4000",
    APP_URL: "http://localhost:3000",
    ADMIN_EMAIL: "admin@example.com",
    ADMIN_PASSWORD: secret(),
  });

  const app = new URL(env.DATABASE_URL);
  await withClient(`postgresql://postgres:${creds.app}@localhost:${CLUSTERS.app}/postgres`, async (c) => {
    await ensureRole(c, app.username, decodeURIComponent(app.password), "CREATEDB");
    await ensureDatabase(c, app.pathname.slice(1), app.username);
  });
  console.log(`✓ application database ready`);
  await sandboxSetup(`postgresql://postgres:${creds.sandbox}@localhost:${CLUSTERS.sandbox}/postgres`, env);
  console.log(`\nAdmin login: ${env.ADMIN_EMAIL} (password is ADMIN_PASSWORD in .env)`);
}

const [cmd, flag] = process.argv.slice(2);
if (existsSync(envFile)) process.loadEnvFile(envFile);

switch (cmd) {
  case "init":
    await init();
    break;
  case "start":
    if (flag === "--if-local" && !hasLocalClusters()) break;
    if (!hasLocalClusters()) fail("No local databases yet. Run `npm run setup` first.");
    for (const name of Object.keys(CLUSTERS)) start(name);
    break;
  case "stop":
    for (const name of Object.keys(CLUSTERS)) if (existsSync(clusterDir(name))) stop(name);
    break;
  case "status":
    for (const name of Object.keys(CLUSTERS))
      console.log(`${name}: ${existsSync(clusterDir(name)) ? (running(name) ? "running" : "stopped") : "not created"}`);
    break;
  case "sandbox-setup": {
    const creds = existsSync(credsFile) ? JSON.parse(readFileSync(credsFile, "utf8")) : {};
    const adminUrl =
      process.env.SANDBOX_ADMIN_URL ?? (creds.sandbox && `postgresql://postgres:${creds.sandbox}@localhost:${CLUSTERS.sandbox}/postgres`);
    if (!adminUrl) fail("Set SANDBOX_ADMIN_URL to a superuser connection for the sandbox server.");
    await sandboxSetup(adminUrl, { ...readEnv(), ...process.env });
    break;
  }
  default:
    console.log("Usage: node scripts/db.mjs init | start [--if-local] | stop | status | sandbox-setup");
}
